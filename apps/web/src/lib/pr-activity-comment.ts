/**
 * PR activity comment — the "buildd is on it" surface.
 *
 * One sticky comment per pull request, edited in place, so a human watching the
 * PR can see that an agent picked the work up without opening the dashboard:
 * reviewer dispatched, CI failure being fixed, review feedback being applied,
 * escalation to a human.
 *
 * The comment carries its own history in a hidden state block
 * (`<!-- buildd-activity-state:{...} -->`), so appending an entry needs no
 * schema column — we read the existing comment, append, and PATCH it back.
 *
 * Every function here is best-effort: a GitHub failure logs and returns
 * `{ action: 'failed' }`. Posting a status comment must never break the
 * lifecycle step that triggered it.
 */

import { DEFAULT_TIMEZONE, formatStamp } from '@buildd/core/timezone';

export const ACTIVITY_COMMENT_MARKER = '<!-- buildd-activity -->';

/**
 * Animated spinner shown in the header while buildd is mid-flight.
 *
 * GitHub routes comment images through its camo proxy, which passes animated
 * GIFs through untouched — animated SVG and CSS do not survive comment
 * sanitization, so a GIF is the only thing that actually moves. The asset is
 * generated by `scripts/generate-pr-spinner-gif.ts`.
 *
 * camo fetches the image server-side, so the origin must be publicly
 * reachable: a localhost dev URL would render as a broken image on GitHub.
 * Anything that isn't a public https origin falls back to production.
 */
function assetOrigin(): string {
  const configured = process.env.NEXT_PUBLIC_APP_URL;
  const usable =
    configured?.startsWith('https://') &&
    !configured.includes('localhost') &&
    !configured.includes('127.0.0.1');
  return usable ? configured!.replace(/\/$/, '') : 'https://buildd.dev';
}

export const SPINNER_PATH = '/github/pr-working.gif';
const STATE_PREFIX = '<!-- buildd-activity-state:';
const STATE_SUFFIX = ' -->';

/** Entries older than this fall off the log so the comment stays readable. */
export const MAX_ACTIVITY_ENTRIES = 12;

export type PrActivityKind =
  | 'reviewing'
  | 'review_approved'
  | 'review_approved_awaiting_human'
  | 'review_changes_requested'
  | 'review_escalated'
  | 'human_review_required'
  | 'ci_fixing'
  | 'ci_exhausted'
  | 'changes_pushed'
  | 'review_superseded_by_merge'
  | 'merged'
  | 'closed_unmerged';

export interface PrActivityEntry {
  kind: PrActivityKind;
  /** One-line qualifier rendered after the headline (e.g. "attempt 2 of 3"). */
  detail?: string | null;
  /** Link rendered alongside the entry (CI run, commit, task). */
  url?: string | null;
  /** ISO timestamp. Defaults to now. */
  at?: string;
}

interface Presentation {
  icon: string;
  /**
   * True while buildd still has work in hand for this PR. Drives the animated
   * header spinner, so movement always means "an agent is on it right now" —
   * a terminal state must never keep spinning.
   */
  working: boolean;
  /** Short label used in both the headline and the log line. */
  label: string;
  /** Sentence under the headline explaining what buildd is doing right now. */
  status: string;
}

