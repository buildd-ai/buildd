#!/usr/bin/env bun
/**
 * Writes docs/design/terms.md from the terms catalog (packages/shared/src/terms.ts),
 * the same way `specs:check` regenerates docs/specs/INDEX.md, so the doc can
 * never drift from the words the surfaces read.
 *
 *   bun run terms:doc           # rewrite docs/design/terms.md
 *   bun run terms:doc --check   # fail if it is stale (CI, pre-commit)
 */
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { BANNED_WORDS, NOUNS, TERMS, type InternalRef } from '../packages/shared/src/terms';

export const TERMS_DOC = 'docs/design/terms.md';

/** Checkout line endings do not change generated content. */
export function termsDocIsCurrent(have: string, want = renderTermsDoc()): boolean {
  return have.replace(/\r\n/g, '\n') === want.replace(/\r\n/g, '\n');
}

const cell = (s: string) => s.replace(/\|/g, '\\|');
const ref = (r: InternalRef) => `\`${r.kind}:${r.value}\`${r.when ? ` (${r.when})` : ''}`;

export function renderTermsDoc(): string {
  const lines = [
    '<!-- Generated by `bun run terms:doc` from packages/shared/src/terms.ts. Do not edit by hand. -->',
    '',
    '# Terms catalog',
    '',
    'Every state shown to a person reads its word from `packages/shared/src/terms.ts`: the web dashboard, `buildd top`,',
    'runner CLI output, MCP replies, notifications and PR activity comments. The internal names on the right are never',
    'renamed; the catalog maps them. A surface may append detail ("Merged · #4955"), never a synonym. The terminal form may',
    'shorten the word, never re-word it.',
    '',
    '| Key | Word | Terminal | Means | Lifted by | Maps from |',
    '|---|---|---|---|---|---|',
  ];
  for (const t of Object.values(TERMS)) {
    lines.push(`| \`${t.key}\` | ${t.glyph ? `${t.glyph} ` : ''}${cell(t.word)} | \`${cell(t.short)}\` | ${cell(t.means)} | ${cell(t.liftedBy ?? '')} | ${t.from.map(ref).join(', ')} |`);
  }
  lines.push('', '## What runs the work', '', 'One noun each. "Worker" is the internal row behind an agent and "seat" an old billing word; neither is shown to a person.', '', '| Noun | Means |', '|---|---|');
  for (const n of Object.values(NOUNS)) lines.push(`| ${cell(n.word)} | ${cell(n.means)} |`);
  lines.push('', '## Words never shown as a state', '', '`bun run copy:check` counts these (rule `catalog-word`). MCP replies are read as an agent reads them: a word marked "agents may" is not counted there.', '', '| Pattern | Say instead | Why |', '|---|---|---|');
  for (const b of BANNED_WORDS) lines.push(`| \`${cell(b.word.source)}\` | ${cell(b.use)}${b.agentsMay ? ' (agents may)' : ''} | ${cell(b.why)} |`);
  return lines.join('\n') + '\n';
}

if (import.meta.main) {
  const want = renderTermsDoc();
  const have = existsSync(TERMS_DOC) ? readFileSync(TERMS_DOC, 'utf8').replace(/\r\n/g, '\n') : '';
  if (process.argv.includes('--check')) {
    if (!termsDocIsCurrent(have, want)) {
      console.error(`❌ ${TERMS_DOC} is stale. Run \`bun run terms:doc\` and commit it.`);
      process.exit(1);
    }
    console.log(`✅ ${TERMS_DOC} is current.`);
  } else if (!termsDocIsCurrent(have, want)) {
    writeFileSync(TERMS_DOC, want);
    console.log(`✅ Wrote ${TERMS_DOC}.`);
  } else console.log(`✅ ${TERMS_DOC} is current.`);
}
