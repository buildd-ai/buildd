#!/usr/bin/env bun
/**
 * Print the SQL that sets up the read-only role brokered production reads run
 * as (`query_database`, apps/web/src/lib/capability-database-query.ts):
 *
 *   bun scripts/query-role-grants.ts > query-role.sql
 *   psql "$OWNER_URL" -v query_role_password="<new password>" -f query-role.sql
 *
 * then set BUILDD_QUERY_DATABASE_URL to that role's connection string in the
 * web app's environment. Re-run after the allowlist changes: it revokes
 * everything and grants SELECT on exactly DATABASE_QUERY_TABLES again.
 *
 * Create the role here, in SQL, not in the Neon console: a console-created
 * role is made a member of neon_superuser, which reads every table. The script
 * revokes that membership in case the role already exists.
 *
 * The output holds no credential; the password comes from a psql variable.
 */
import { DATABASE_QUERY_LIMITS, DATABASE_QUERY_ROLE, DATABASE_QUERY_TABLES } from '../apps/web/src/lib/capability-database-query';

const IDENT_RE = /^[a-z_][a-z0-9_]*$/;

/** The plain statements (no psql meta-commands) that narrow an existing role to the allowlist. */
export function queryRoleGrantStatements(role: string = DATABASE_QUERY_ROLE, tables: readonly string[] = DATABASE_QUERY_TABLES): string[] {
  for (const n of [role, ...tables]) if (!IDENT_RE.test(n)) throw new Error(`not a plain identifier: ${n}`);
  return [
    `ALTER ROLE ${role} NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS`,
    `DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'neon_superuser') THEN EXECUTE 'REVOKE neon_superuser FROM ${role}'; END IF; END $$`,
    `REVOKE ALL ON ALL TABLES IN SCHEMA public FROM ${role}`,
    `REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM ${role}`,
    `REVOKE CREATE ON SCHEMA public FROM ${role}`,
    `GRANT USAGE ON SCHEMA public TO ${role}`,
    ...tables.map(t => `GRANT SELECT ON public.${t} TO ${role}`),
    `ALTER ROLE ${role} SET default_transaction_read_only = on`,
    `ALTER ROLE ${role} SET statement_timeout = ${DATABASE_QUERY_LIMITS.statementTimeoutMs}`,
    `ALTER ROLE ${role} SET search_path = public`,
  ];
}

export function queryRoleSql(role: string = DATABASE_QUERY_ROLE, tables: readonly string[] = DATABASE_QUERY_TABLES): string {
  const statements = queryRoleGrantStatements(role, tables);
  return [
    `-- Read-only role for buildd's brokered production reads. Generated by scripts/query-role-grants.ts.`,
    `\\set ON_ERROR_STOP on`,
    `SELECT format('CREATE ROLE ${role} LOGIN PASSWORD %L', :'query_role_password')`,
    `  WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${role}') \\gexec`,
    ...statements.map(s => `${s};`),
    '',
  ].join('\n');
}

if (import.meta.main) process.stdout.write(queryRoleSql());
