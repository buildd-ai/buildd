/**
 * Unmergeable surfaces: the one list of paths where two tasks working at the
 * same time produce a conflict the merge tooling cannot settle (runner
 * pre-merge + mergiraf, mission refresh, the conflict resolver). Overlap on
 * any other file starts both tasks and is settled at merge.
 *
 * The claim route holds an overlapping task only when the shared paths touch
 * this list, a migration namespace in any repo (`isMigrationPath`), or a
 * surface the workspace marks serialized (`lib/hard-overlap-surfaces.ts`).
 * Spec: Claim Overlap Scheduling, Capability 6.
 *
 * Pattern forms:
 *  - `dir/**`: the directory and everything under it;
 *  - a pattern with no `/` (`bun.lock`, `*.snap`): the basename at any depth;
 *  - anything else: that exact repo path.
 *
 * Pure, no DB.
 */
import { stripTrailingSep } from './path-overlap';

export interface UnmergeableSurface {
  pattern: string;
  why: string;
}

export const UNMERGEABLE_SURFACES: readonly UnmergeableSurface[] = [
  { pattern: 'packages/core/drizzle/**', why: 'migration files, journal and snapshots: two new indexes collide' },
  { pattern: 'packages/core/db/schema.ts', why: 'the schema each migration is generated from' },
  { pattern: 'bun.lock', why: 'lockfile: regenerated, never merged by hand' },
  { pattern: 'bun.lockb', why: 'lockfile: binary' },
  { pattern: 'package-lock.json', why: 'lockfile' },
  { pattern: 'yarn.lock', why: 'lockfile' },
  { pattern: 'pnpm-lock.yaml', why: 'lockfile' },
  { pattern: 'Cargo.lock', why: 'lockfile' },
  { pattern: 'poetry.lock', why: 'lockfile' },
  { pattern: 'Gemfile.lock', why: 'lockfile' },
  { pattern: 'go.sum', why: 'lockfile' },
  { pattern: 'docs/specs/INDEX.md', why: 'generated from every spec frontmatter' },
  { pattern: '*.snap', why: 'generated test snapshot' },
  { pattern: 'next-env.d.ts', why: 'generated by next' },
];

function globBasename(pattern: string, base: string): boolean {
  const re = new RegExp(`^${pattern.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '[^/]*').replace(/\?/g, '[^/]')}$`);
  return re.test(base);
}

function matches(path: string, pattern: string): boolean {
  if (pattern.endsWith('/**')) {
    const dir = pattern.slice(0, -3);
    return path === dir || path.startsWith(dir + '/');
  }
  if (!pattern.includes('/')) return globBasename(pattern, path.split('/').pop() ?? '');
  return path === pattern;
}

/** The list entry a path falls under, or null. */
export function unmergeableSurfaceOf(path: string): UnmergeableSurface | null {
  const p = stripTrailingSep(path.trim()).replace(/^\/+/, '');
  if (!p) return null;
  return UNMERGEABLE_SURFACES.find(s => matches(p, s.pattern)) ?? null;
}

/** The paths (of those given) that fall on an unmergeable surface, in order. */
export function unmergeablePaths(paths: readonly string[]): string[] {
  return paths.filter(p => unmergeableSurfaceOf(p) !== null);
}
