/**
 * Files in this repo that a script writes, never a person.
 *
 * A merge conflict in one of these is resolved by regenerating it
 * (`scripts/resolve-generated-conflicts.ts`), not by reading both sides.
 * `isCiVerifiedGeneratedPath` is the subset CI regenerates and compares for
 * equality, so a wrong resolution cannot merge green: a refresh PR's novel
 * delta leaves them out (docs/specs/workflow-state-kernel.md §5.9). Two
 * generated kinds stay reviewed. The design-check baseline is only ratcheted
 * (counts must not exceed it), so a raised value would pass CI. A migration
 * `.sql` may carry a hand-written step that `db:generate` would never emit,
 * which the up-to-date check cannot see; a migration the merge only moved to a
 * free index is recognised separately, by content (`renumberedMigrations`).
 */

/** Regenerated by `bun run specs:check`; `specs:lint` fails a stale copy. */
export const SPECS_INDEX_PATH = 'docs/specs/INDEX.md';
/** Written by `bun db:generate`; the build job fails a schema that would generate more. */
export const DRIZZLE_DIR = 'packages/core/drizzle/';
/** The journal and snapshots: regenerated in full, so the up-to-date check covers them. */
export const DRIZZLE_META_DIR = 'packages/core/drizzle/meta/';
/** Lowered by `bun run design:check --update`; CI checks counts against it, not equality. */
export const DESIGN_CHECK_BASELINE_PATH = 'scripts/design-check.baseline.json';

export function isCiVerifiedGeneratedPath(path: string): boolean {
  return path === SPECS_INDEX_PATH || path.startsWith(DRIZZLE_META_DIR);
}

export function isMigrationSqlPath(path: string): boolean {
  return path.startsWith(DRIZZLE_DIR) && !path.startsWith(DRIZZLE_META_DIR) && path.endsWith('.sql');
}

export function isGeneratedArtifactPath(path: string): boolean {
  return isCiVerifiedGeneratedPath(path) || path.startsWith(DRIZZLE_DIR) || path === DESIGN_CHECK_BASELINE_PATH;
}
