/**
 * The generated repo copy of a native spec (docs/specs/living-specs.md §18,
 * D-13, R-14, R-15, R-16). Pure: render a copy from an approved revision, and
 * verify a file that claims to be one.
 *
 * The approved text is the revision's body exactly as stored, which may open
 * with an intent frontmatter block (`title`, `summary`, `related`, `keywords`,
 * `supersedes`). Only it is approved and only it is hashed (`content_hash`).
 * The mechanical fields (`status`, `owner`, `last_verified`, `domain`,
 * `surfaces`, `verified_by`, `assertions`) are the metadata block, written
 * after a marker line and hashed on their own (`metadata_hash`). Three
 * generated lines close the frontmatter. A copy is laid out so the approved
 * text can be cut back out of it byte for byte:
 *
 *   ---
 *   <the body's own frontmatter lines, verbatim>     approved text
 *   # generated by buildd from spec <short id> ...   marker
 *   status: ...                                       metadata block
 *   generated_from: <short id>@r<revision>
 *   content_hash: <sha256 of the approved text>
 *   metadata_hash: <sha256 of the metadata block>
 *   ---
 *   <the body after its frontmatter, verbatim>       approved text
 *
 * The full spec id is never written: only its 8-character short id.
 */
import { contentHash } from './hash';

export const INTENT_FIELDS = ['title', 'summary', 'related', 'keywords', 'supersedes'] as const;
/** Mechanical fields a body may not carry: they live in the metadata block (R-14). */
export const METADATA_FIELDS = ['status', 'last_verified', 'domain', 'surfaces', 'verified_by', 'assertions'] as const;
export const GENERATED_FIELDS = ['generated_from', 'content_hash', 'metadata_hash'] as const;
/** Every marker line starts with this; a YAML comment, so frontmatter parsers skip it. */
export const REPO_COPY_MARKER = '# generated by buildd from spec';

export type AssertionValue = string | number | boolean;

/** The metadata block of a spec (R-14): updatable without a revision (R-31). */
export interface SpecMetadata {
  owner?: string;
  last_verified?: string;
  surfaces?: string[];
  verified_by?: string[];
  assertions?: Array<Record<string, AssertionValue>>;
}

export interface RepoCopyInput {
  /** The spec's 8-character short id. */
  shortId: string;
  revision: number;
  /** The spec's title, written to the metadata block only when the body states none. */
  title: string;
  /** The approved revision's body, exactly as stored. */
  body: string;
  metadata: SpecMetadata;
  /** Derived from the spec's filed area (R-32). */
  domain: string;
  /** `active` once `verified_by` names a test, else `draft` (SPEC-FORMAT rule 9). */
  status: 'active' | 'draft';
  /** Fallbacks for fields the metadata block leaves empty. */
  defaultOwner: string;
  defaultLastVerified: string;
}

export type RepoCopy = { ok: true; text: string; contentHash: string; metadataHash: string };
export type RepoCopyRefusal = { ok: false; reason: 'bad_short_id' | 'mechanical_in_body' | 'bad_metadata' | 'not_round_trip'; message: string };

const SHORT_ID = /^[0-9a-f]{8}$/;
const KEY_LINE = /^([A-Za-z_][A-Za-z0-9_]*):/;

/** The short id of a spec: the first 8 hex characters of its id. */
export const specShortId = (specId: string): string => specId.replace(/-/g, '').slice(0, 8).toLowerCase();

/** A body's own frontmatter (inner text, each line ending in a newline) and what follows it. */
export function splitBodyFrontmatter(body: string): { inner: string; rest: string } {
  if (!body.startsWith('---\n')) return { inner: '', rest: body };
  const close = body.indexOf('\n---\n', 3);
  if (close === -1) return { inner: '', rest: body };
  return { inner: body.slice(4, close + 1), rest: body.slice(close + 5) };
}

const topKeys = (inner: string): string[] =>
  inner.split('\n').map((l) => KEY_LINE.exec(l)?.[1]).filter((k): k is string => !!k);

const SAFE_SCALAR = /^[A-Za-z0-9_./@+-][A-Za-z0-9_ ./@+()-]*$/;
/** A scalar as YAML: plain when unambiguous, else JSON (a valid YAML double-quoted string). */
function scalar(v: AssertionValue): string {
  if (typeof v !== 'string') return String(v);
  return SAFE_SCALAR.test(v) && !/^(true|false|null|yes|no|~)$/i.test(v) && !/^[\d.]+$/.test(v) && !v.endsWith(' ') ? v : JSON.stringify(v);
}

function list(items: readonly string[] | undefined): string {
  for (const i of items ?? []) if (/[,[\]\n]/.test(i)) throw new Error(`a list item may not contain a comma, a bracket or a newline: ${i}`);
  return `[${(items ?? []).join(', ')}]`;
}

/** The metadata block lines, in their fixed order. */
export function metadataBlock(input: Pick<RepoCopyInput, 'metadata' | 'domain' | 'status' | 'defaultOwner' | 'defaultLastVerified' | 'title'>, skip: ReadonlySet<string>): string[] {
  const m = input.metadata;
  const one = (s: string, what: string) => {
    if (/\n/.test(s) || !s.trim()) throw new Error(`${what} must be one non-empty line`);
    return s.trim();
  };
  const lines = [`status: ${input.status}`];
  if (!skip.has('owner')) lines.push(`owner: ${one(m.owner ?? input.defaultOwner, 'owner')}`);
  if (!skip.has('title')) lines.push(`title: ${one(input.title, 'title')}`);
  lines.push(`last_verified: ${one(m.last_verified ?? input.defaultLastVerified, 'last_verified')}`);
  lines.push(`domain: ${one(input.domain, 'domain')}`);
  lines.push(`surfaces: ${list(m.surfaces)}`);
  lines.push(`verified_by: ${list(m.verified_by)}`);
  if (m.assertions?.length) {
    lines.push('assertions:');
    for (const a of m.assertions) {
      const entries = Object.entries(a);
      if (!entries.length) throw new Error('an assertion needs at least one field');
      entries.forEach(([k, v], i) => {
        if (!KEY_LINE.test(`${k}:`)) throw new Error(`assertion field "${k}" is not a plain key`);
        lines.push(`${i === 0 ? '  - ' : '    '}${k}: ${scalar(v)}`);
      });
    }
  }
  return lines;
}

const marker = (shortId: string) => `${REPO_COPY_MARKER} ${shortId}: edit it at /app/specs/${shortId}, not here`;
const joinLines = (lines: readonly string[]) => (lines.length ? `${lines.join('\n')}\n` : '');

/** Render the repo copy of one approved revision. Refuses anything that would not verify. */
export async function renderRepoCopy(input: RepoCopyInput): Promise<RepoCopy | RepoCopyRefusal> {
  if (!SHORT_ID.test(input.shortId)) return { ok: false, reason: 'bad_short_id', message: 'the short id must be 8 lowercase hex characters' };
  const { inner, rest } = splitBodyFrontmatter(input.body);
  const keys = topKeys(inner);
  const mechanical = keys.filter((k) => (METADATA_FIELDS as readonly string[]).includes(k) || (GENERATED_FIELDS as readonly string[]).includes(k));
  if (mechanical.length) {
    return { ok: false, reason: 'mechanical_in_body', message: `the body's frontmatter carries ${mechanical.join(', ')}; those are metadata, kept outside the approved text` };
  }
  let block: string[];
  try {
    block = metadataBlock(input, new Set(keys));
  } catch (err) {
    return { ok: false, reason: 'bad_metadata', message: err instanceof Error ? err.message : String(err) };
  }
  const approvedHash = await contentHash(input.body);
  const metadataHash = await contentHash(joinLines(block));
  const text = `---\n${inner}${joinLines([
    marker(input.shortId),
    ...block,
    `generated_from: ${input.shortId}@r${input.revision}`,
    `content_hash: ${approvedHash}`,
    `metadata_hash: ${metadataHash}`,
  ])}---\n${rest}`;
  const back = await verifyRepoCopy(text);
  if (!back.generated || !back.ok || back.approvedText !== input.body) {
    return { ok: false, reason: 'not_round_trip', message: 'this body cannot be cut back out of its copy exactly (an empty or unusual frontmatter block); it is not generated' };
  }
  return { ok: true, text, contentHash: approvedHash, metadataHash };
}

export type RepoCopyCheck =
  | { generated: false }
  | {
    generated: true;
    shortId: string;
    revision: number | null;
    /** Both hashes match what the file carries. */
    ok: boolean;
    bodyOk: boolean;
    metadataOk: boolean;
    /** What is wrong, in words, when not ok. */
    problems: string[];
    approvedText: string;
  };

/**
 * Whether a file is a generated copy and, if so, whether it is unedited: the
 * approved text cut back out hashes to `content_hash` and the metadata block
 * to `metadata_hash`. A file with `generated_from` that cannot be cut apart is
 * reported, never passed.
 */
export async function verifyRepoCopy(text: string): Promise<RepoCopyCheck> {
  if (!text.startsWith('---\n')) return { generated: false };
  const close = text.indexOf('\n---\n', 3);
  const end = close === -1 ? (text.endsWith('\n---') ? text.length - 4 : -1) : close;
  if (end === -1) return { generated: false };
  const lines = text.slice(4, end + 1).split('\n').slice(0, -1);
  const genIdx = lines.findIndex((l) => l.startsWith('generated_from:'));
  if (genIdx === -1) return { generated: false };
  const from = /^generated_from:\s*([0-9a-f]{8})(?:@r(\d+))?\s*$/.exec(lines[genIdx]!);
  const shortId = from?.[1] ?? (/^generated_from:\s*(\S{1,16})/.exec(lines[genIdx]!)?.[1] ?? '');
  const revision = from?.[2] ? Number(from[2]) : null;
  const problems: string[] = [];
  const markerIdx = lines.findIndex((l) => l.startsWith(REPO_COPY_MARKER));
  const claimedContent = /^content_hash:\s*([0-9a-f]{64})\s*$/.exec(lines[genIdx + 1] ?? '')?.[1];
  const claimedMeta = /^metadata_hash:\s*([0-9a-f]{64})\s*$/.exec(lines[genIdx + 2] ?? '')?.[1];
  if (!from) problems.push('generated_from is not "<short id>@r<revision>"');
  if (markerIdx === -1 || markerIdx > genIdx) problems.push('the generated marker line is missing or moved');
  if (!claimedContent || !claimedMeta || lines.length !== genIdx + 3) problems.push('the three generated lines (generated_from, content_hash, metadata_hash) must close the frontmatter, in that order');
  if (problems.length) return { generated: true, shortId, revision, ok: false, bodyOk: false, metadataOk: false, problems, approvedText: '' };

  const intent = lines.slice(0, markerIdx);
  const rest = close === -1 ? '' : text.slice(close + 5);
  const approvedText = intent.length ? `---\n${joinLines(intent)}---\n${rest}` : rest;
  const bodyOk = (await contentHash(approvedText)) === claimedContent;
  const metadataOk = (await contentHash(joinLines(lines.slice(markerIdx + 1, genIdx)))) === claimedMeta;
  if (!bodyOk) problems.push('the approved text (body and intent frontmatter) does not match content_hash');
  if (!metadataOk) problems.push('the metadata block (status, owner, domain, surfaces, verified_by, assertions, last_verified) does not match metadata_hash');
  return { generated: true, shortId, revision, ok: bodyOk && metadataOk, bodyOk, metadataOk, problems, approvedText };
}
