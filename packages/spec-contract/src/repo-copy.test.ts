import { describe, expect, it } from 'bun:test';
import { contentHash } from './hash';
import { renderRepoCopy, specShortId, verifyRepoCopy, type RepoCopyInput } from './repo-copy';
import { lintSpecFile, parseSpecFrontmatter } from './repo-spec';

// docs/specs/living-specs.md §18: R-14, R-15, R-16, AC-74, AC-75.

const BODY = `---
title: Widget Export
summary: A widget export MUST write one file per widget.
related: [release-flow]
keywords: [export, widget]
---
# Widget Export

**Capability statement**: Exports MUST be complete.

- AC-1: GIVEN a widget WHEN exported THEN one file is written.
`;

const SPEC_ID = '1a2b3c4d-0000-4000-8000-00000000abcd';

function input(over: Partial<RepoCopyInput> = {}): RepoCopyInput {
  return {
    shortId: specShortId(SPEC_ID), revision: 3, title: 'Widget Export', body: BODY,
    metadata: { verified_by: ['apps/web/src/lib/widget.test.ts'], surfaces: ['apps/web/src/lib/widget.ts'], assertions: [{ id: 'export-route', type: 'route', method: 'GET', path: '/api/widgets/[id]' }] },
    domain: 'integrations', status: 'active', defaultOwner: 'buildd', defaultLastVerified: '2026-10-13',
    ...over,
  };
}

async function render(over: Partial<RepoCopyInput> = {}) {
  const r = await renderRepoCopy(input(over));
  if (!r.ok) throw new Error(r.message);
  return r;
}

describe('renderRepoCopy', () => {
  it('writes the approved text, the metadata block and three generated lines; the approved text hashes to the revision hash (AC-74)', async () => {
    const r = await render();
    expect(r.contentHash).toBe(await contentHash(BODY));
    expect(r.text).toContain(`generated_from: 1a2b3c4d@r3\ncontent_hash: ${r.contentHash}\nmetadata_hash: ${r.metadataHash}\n---\n# Widget Export`);
    expect(r.text).toContain('domain: integrations');
    expect(r.text).toContain('  - id: export-route\n    type: route\n    method: GET\n    path: "/api/widgets/[id]"');
    const back = await verifyRepoCopy(r.text);
    expect(back).toMatchObject({ generated: true, shortId: '1a2b3c4d', revision: 3, ok: true });
    if (back.generated) expect(back.approvedText).toBe(BODY);
  });

  it('never writes the full spec id', async () => {
    const r = await render();
    expect(r.text).not.toContain(SPEC_ID);
    expect(r.text).not.toMatch(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/);
  });

  it('passes the repo spec lint: the frontmatter parses with every required field', async () => {
    const r = await render();
    const { fm, body } = parseSpecFrontmatter(r.text);
    expect(fm).toMatchObject({ title: 'Widget Export', status: 'active', owner: 'buildd', domain: 'integrations', last_verified: '2026-10-13' });
    const lint = lintSpecFile('widget-export', fm, body, { domains: new Set(['integrations']), exists: () => true, now: Date.parse('2026-10-14') });
    expect(lint.errors).toEqual([]);
  });

  it('a body with no frontmatter: title and owner come from the metadata block, and the body is the approved text', async () => {
    const plain = '# Plain\n\nSome text.\n';
    const r = await render({ body: plain, title: 'Plain' });
    expect(r.text.startsWith('---\n# generated by buildd from spec 1a2b3c4d')).toBe(true);
    expect(r.text.endsWith(`---\n${plain}`)).toBe(true);
    const back = await verifyRepoCopy(r.text);
    expect(back.generated && back.ok && back.approvedText === plain).toBe(true);
  });

  // The first native copy (a body with no frontmatter, as a native spec's body
  // usually is) failed specs:lint on `frontmatter missing summary`.
  const lintCopy = (text: string) => {
    const { fm, body } = parseSpecFrontmatter(text);
    return { fm, lint: lintSpecFile('runner-login', fm, body, { domains: new Set(['runners']), exists: () => true, now: Date.parse('2026-10-14') }) };
  };
  const NATIVE = '# Runner login\n\nContext: a runner uses its own login (`host-seat.ts`). It never says which. More prose here.\n\n## Requirements\n\n- R-1: A runner detects its login.\n';

  it('a body with no frontmatter: the copy carries a summary, the first prose sentence, and passes specs:lint', async () => {
    const r = await render({ body: NATIVE, title: 'Runner login', domain: 'runners', status: 'draft', metadata: {} });
    const { fm, lint } = lintCopy(r.text);
    expect(lint.errors).toEqual([]);
    expect(fm?.summary).toBe('Context: a runner uses its own login (`host-seat.ts`).');
    const back = await verifyRepoCopy(r.text);
    expect(back.generated && back.ok && back.approvedText === NATIVE).toBe(true);
  });

  it('the metadata block summary wins over the body prose', async () => {
    const r = await render({ body: NATIVE, title: 'Runner login', domain: 'runners', status: 'draft', metadata: { summary: 'A runner MUST name the login its agents use.' } });
    expect(lintCopy(r.text).fm?.summary).toBe('A runner MUST name the login its agents use.');
    expect((await verifyRepoCopy(r.text)).generated).toBe(true);
  });

  it('a body that states its own summary is not given a second one', async () => {
    const r = await render();
    expect(r.text.match(/^summary:/gm)).toHaveLength(1);
  });

  it('a summary is one line, quoted so YAML reads it as one string, and never a list', async () => {
    const body = '# Odd\n\n[Draft] a: b # not a comment, "quoted" too\nsecond line of the same paragraph.\n';
    const r = await render({ body, title: 'Odd', domain: 'runners', status: 'draft', metadata: {} });
    const line = r.text.split('\n').find((l) => l.startsWith('summary:'))!;
    expect(line).toBe('summary: \'[Draft] a: b # not a comment, "quoted" too second line of the same paragraph.\'');
    expect(lintCopy(r.text).lint.errors).toEqual([]);
    expect((await verifyRepoCopy(r.text)).generated && (await verifyRepoCopy(r.text) as { ok: boolean }).ok).toBe(true);
  });

  it('a body with no prose falls back to the title for its summary', async () => {
    const r = await render({ body: '# Only\n\n- R-1: a thing.\n', title: 'Only', domain: 'runners', status: 'draft', metadata: {} });
    expect(lintCopy(r.text).fm?.summary).toBe('Only');
  });

  it('refuses a body whose frontmatter carries a mechanical field', async () => {
    const r = await renderRepoCopy(input({ body: '---\ntitle: X\ndomain: tasks\n---\n# X\n' }));
    expect(r).toMatchObject({ ok: false, reason: 'mechanical_in_body' });
  });

  it('a metadata change moves only metadata_hash', async () => {
    const a = await render();
    const b = await render({ metadata: { ...input().metadata, verified_by: ['apps/web/src/lib/widget.test.ts', 'apps/web/src/lib/widget-2.test.ts'] } });
    expect(b.contentHash).toBe(a.contentHash);
    expect(b.metadataHash).not.toBe(a.metadataHash);
  });
});

describe('verifyRepoCopy refuses a hand edit (AC-75)', () => {
  it('to the body', async () => {
    const r = await render();
    const v = await verifyRepoCopy(r.text.replace('one file is written', 'two files are written'));
    expect(v).toMatchObject({ generated: true, ok: false, bodyOk: false, metadataOk: true });
  });

  it('to an intent field', async () => {
    const r = await render();
    const v = await verifyRepoCopy(r.text.replace('keywords: [export, widget]', 'keywords: [export]'));
    expect(v).toMatchObject({ generated: true, ok: false, bodyOk: false });
  });

  it('to the metadata, domain included', async () => {
    const r = await render();
    expect(await verifyRepoCopy(r.text.replace('domain: integrations', 'domain: tasks'))).toMatchObject({ ok: false, bodyOk: true, metadataOk: false });
    expect(await verifyRepoCopy(r.text.replace('status: active', 'status: draft'))).toMatchObject({ ok: false, metadataOk: false });
  });

  it('to the generated lines themselves', async () => {
    const r = await render();
    const v = await verifyRepoCopy(r.text.replace(/content_hash: [0-9a-f]{64}/, `content_hash: ${'0'.repeat(64)}`));
    expect(v).toMatchObject({ ok: false, bodyOk: false });
    const moved = await verifyRepoCopy(r.text.replace(/\n(content_hash: [0-9a-f]{64})/, '\nextra: 1\n$1'));
    expect(moved).toMatchObject({ generated: true, ok: false });
  });

  it('a file without generated_from is not a copy', async () => {
    expect(await verifyRepoCopy('---\ntitle: X\n---\n# X\n')).toEqual({ generated: false });
    expect(await verifyRepoCopy('# X\n')).toEqual({ generated: false });
  });
});
